/** Each card/expand-modal shows one piece of work, so its category badge reads better singular (e.g. "Website" not "Websites") - unlike the filter tabs, which pair the label with a count and stay plural. */
const PORTFOLIO_ITEM_CATEGORY_LABEL_OVERRIDES: Partial<Record<PortfolioCategoryId, string>> = {
  websites: "Website",
};

export function portfolioItemCategoryLabel(category: PortfolioCategoryId): string {
  return PORTFOLIO_ITEM_CATEGORY_LABEL_OVERRIDES[category] ?? portfolioCategories.find(c => c.id === category)?.label ?? category;
}

export type PortfolioItem = {
  slug: string;
  category: PortfolioCategoryId;
  title: string;
  client?: string;
  type: "website" | "logo" | "deck" | "other";
  thumbnail: string;
  thumbnailAlt: string;
  description: string;
  isPlaceholder?: boolean;
  /** Only for type: "website" — tall full-page image used by the scroll-simulation preview. */
  fullPageImage?: string;
  /** Clean client logo shown by default on the grid card; hovering crossfades to `thumbnail`. Used for "website" and "deck" items whose thumbnail is a busy hero/cover rather than a plain logo. */
  logoThumbnail?: string;
  /** Set when `logoThumbnail` is itself a full-bleed photo/design (not a plain logo on white) so the card renders it edge-to-edge instead of with logo breathing-room padding. */
  logoFullBleed?: boolean;
  /** Overrides the card's default white letterbox color — for a widescreen slide image whose own background should show through instead of white. */
  cardBackgroundColor?: string;
  /** Additional real deliverable pages shown as a gallery in the expand modal (logo/deck items). Falls back to [thumbnail] if omitted. */
  images?: string[];
};

